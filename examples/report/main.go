// Report writes a one-page PDF with a table and a line chart using pdfreport.
// Native MyGo windows cannot export themselves to PDF, so a native app lays its
// report out with this package.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"strconv"

	"github.com/auron-labs/mygo-framework/pdfreport"
)

type night struct {
	label   string
	hours   float64
	events  int
	minSpO2 float64
}

var nights = []night{
	{"Mon", 7.2, 4, 93},
	{"Tue", 6.8, 7, 91},
	{"Wed", 7.9, 3, 94},
	{"Thu", 6.1, 9, 90},
	{"Fri", 7.4, 5, 92},
	{"Sat", 8.3, 2, 95},
	{"Sun", 7.7, 3, 94},
}

func buildReport() ([]byte, error) {
	r, err := pdfreport.New(pdfreport.Options{Title: "Weekly sleep report", Footer: "Generated by Framework Native"})
	if err != nil {
		return nil, fmt.Errorf("start report: %w", err)
	}
	r.Heading("Weekly sleep report", 20)
	r.Paragraph("Seven nights of recordings. Nights with more events per hour than the weekly average are worth a closer look.")

	rows := make([][]string, len(nights))
	hours := pdfreport.Series{Name: "Hours slept"}
	events := pdfreport.Series{Name: "Events"}
	for i, n := range nights {
		rows[i] = []string{n.label, strconv.FormatFloat(n.hours, 'f', 1, 64), strconv.Itoa(n.events), strconv.FormatFloat(n.minSpO2, 'f', 0, 64) + "%"}
		hours.Points = append(hours.Points, pdfreport.Point{X: float64(i), Y: n.hours})
		events.Points = append(events.Points, pdfreport.Point{X: float64(i), Y: float64(n.events)})
	}
	r.Table([]pdfreport.Column{
		{Title: "Night", Width: 2},
		{Title: "Hours", Width: 1, Right: true},
		{Title: "Events", Width: 1, Right: true},
		{Title: "Lowest SpO2", Width: 2, Right: true},
	}, rows)
	r.LineChart(pdfreport.LineChart{
		Title:  "Hours slept and events per night",
		Series: []pdfreport.Series{hours, events},
		XLabel: func(x float64) string { return nights[int(x)].label },
	})
	data, err := r.Bytes()
	if err != nil {
		return nil, fmt.Errorf("finish report: %w", err)
	}
	return data, nil
}

func main() {
	out := flag.String("o", "report.pdf", "Path of the PDF to write")
	flag.Parse()
	data, err := buildReport()
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, data, 0o600); err != nil {
		log.Fatal(err)
	}
	fmt.Println("wrote", *out)
}
