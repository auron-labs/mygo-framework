const generatedHeader = "// Code generated by framework generate. DO NOT EDIT.\n"

// GenerateConfig controls generated-file comparison and writes.
type GenerateConfig struct {
	Dir   string
	Check bool
}

// GenerateResult reports the complete owned set and files that differed.
type GenerateResult struct {
	Files   []string
	Changed []string
}

// StaleError reports generator-owned files that would change.
type StaleError struct {
	Files []string
}

func (e *StaleError) Error() string {
	return "generated files are stale: " + strings.Join(e.Files, ", ")
}

type generatedFile struct {
	path    string
	content []byte
}

type importData struct {
	Alias string
	Path  string
}

type methodData struct {
	Name        string
	Description string
	Command     string
	Input       string
	Output      string
	Response    string
}

type serviceData struct {
	Name         string
	Type         string
	Resolver     string
	RuntimeLabel string
	Methods      []methodData
}

type desktopData struct {
	Header      string
	Imports     []importData
	ProblemPath string
	RuntimePath string
	Services    []serviceData
}

type bindingData struct {
	Header        string
	BootstrapPath string
	DesktopPath   string
	Services      []serviceData
}

type toolData struct {
	Name        string
	Description string
	PackagePath string
	Service     string
	Method      string
	ReadOnly    bool
	Destructive bool
}

type mcpData struct {
	Header string
	Tools  []toolData
}

// Generate renders, formats, checks, and optionally writes all owned files.
func Generate(ctx context.Context, config GenerateConfig) (GenerateResult, error) {
	if ctx == nil {
		return GenerateResult{}, errors.New("generate framework files: context is required")
	}
	directory := config.Dir
	if directory == "" {
		directory = "."
	}
	methods, err := Discover(ctx, DiscoveryConfig{Dir: directory})
	if err != nil {
		return GenerateResult{}, err
	}
	files, err := renderGeneratedFiles(methods)
	if err != nil {
		return GenerateResult{}, err
	}

	result := GenerateResult{Files: make([]string, 0, len(files))}
	for _, file := range files {
		result.Files = append(result.Files, file.path)
		// #nosec G304 -- file.path comes from the generator's fixed owned-file set.
		existing, err := os.ReadFile(filepath.Join(directory, file.path))
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return GenerateResult{}, fmt.Errorf("read generated file %s: %w", file.path, err)
		}
		if err == nil && !bytes.HasPrefix(existing, []byte(generatedHeader)) {
			return GenerateResult{}, fmt.Errorf("refuse to replace non-generated file %s", file.path)
		}
		if !bytes.Equal(existing, file.content) {
			result.Changed = append(result.Changed, file.path)
		}
	}
	if config.Check && len(result.Changed) > 0 {
		return result, &StaleError{Files: result.Changed}
	}
	for _, file := range files {
		if !slicesContains(result.Changed, file.path) {
			continue
		}
		fullPath := filepath.Join(directory, file.path)
		if err := os.MkdirAll(filepath.Dir(fullPath), 0o750); err != nil {
			return GenerateResult{}, fmt.Errorf("create generated directory for %s: %w", file.path, err)
		}
		// #nosec G306 -- generated Go source should use conventional source-file permissions.
		if err := os.WriteFile(fullPath, file.content, 0o644); err != nil {
			return GenerateResult{}, fmt.Errorf("write generated file %s: %w", file.path, err)
		}
	}
	return result, nil
}

func renderGeneratedFiles(methods []Method) ([]generatedFile, error) {
	modulePath, err := modulePath(methods)
	if err != nil {
		return nil, err
	}
	desktop, services, err := renderDesktop(modulePath, methods)
	if err != nil {
		return nil, err
	}
	bindings, err := renderGo(bindingsTemplate, bindingData{
		Header:        generatedHeader,
		BootstrapPath: modulePath + "/app/bootstrap",
		DesktopPath:   modulePath + "/app/desktop",
		Services:      services,
	})
	if err != nil {
		return nil, fmt.Errorf("render desktop bindings: %w", err)
	}
	tools, err := renderGo(mcpTemplate, mcpData{Header: generatedHeader, Tools: selectedTools(methods)})
	if err != nil {
		return nil, fmt.Errorf("render MCP stubs: %w", err)
	}
	return []generatedFile{
		{path: filepath.ToSlash(filepath.Join("app", "desktop", "framework_generated.go")), content: desktop},
		{path: "framework_bindings_generated.go", content: bindings},
		{path: filepath.ToSlash(filepath.Join("app", "mcp", "framework_generated.go")), content: tools},
	}, nil
}

func renderDesktop(modulePath string, methods []Method) ([]byte, []serviceData, error) {
	selected := make([]Method, 0, len(methods))
	paths := map[string]struct{}{}
	for _, method := range methods {
		if method.Command == "" {
			continue
		}
		selected = append(selected, method)
		paths[method.PackagePath] = struct{}{}
		paths[method.Input.PackagePath] = struct{}{}
		paths[method.Output.PackagePath] = struct{}{}
	}
	aliases := importAliases(paths)
	imports := make([]importData, 0, len(aliases))
	for path, alias := range aliases {
		imports = append(imports, importData{Alias: alias, Path: path})
	}
	sort.Slice(imports, func(i, j int) bool { return imports[i].Path < imports[j].Path })

	grouped := map[string]*serviceData{}
	responses := map[string]tokenPosition{}
	for _, method := range selected {
		key := method.PackagePath + "." + method.Service
		service := grouped[key]
		if service == nil {
			service = &serviceData{
				Name:         method.Service,
				Type:         aliases[method.PackagePath] + "." + method.Service,
				Resolver:     "Resolve" + method.Service,
				RuntimeLabel: strings.ToLower(method.Service),
			}
			grouped[key] = service
		}
		response := strings.TrimSuffix(method.Output.Name, "Output") + "Response"
		if previous, exists := responses[response]; exists {
			return nil, nil, fmt.Errorf("%s: generated response %s conflicts with %s", method.Position, response, previous)
		}
		responses[response] = tokenPosition(method.Position.String())
		service.Methods = append(service.Methods, methodData{
			Name:        method.Name,
			Description: goComment(method.Description),
			Command:     method.Command,
			Input:       aliases[method.Input.PackagePath] + "." + method.Input.Name,
			Output:      aliases[method.Output.PackagePath] + "." + method.Output.Name,
			Response:    response,
		})
	}
	services := make([]serviceData, 0, len(grouped))
	for _, service := range grouped {
		services = append(services, *service)
	}
	sort.Slice(services, func(i, j int) bool { return services[i].Name < services[j].Name })

	content, err := renderGo(desktopTemplate, desktopData{
		Header:      generatedHeader,
		Imports:     imports,
		ProblemPath: modulePath + "/problem",
		RuntimePath: modulePath + "/runtime",
		Services:    services,
	})
	if err != nil {
		return nil, nil, fmt.Errorf("render desktop adapters: %w", err)
	}
	return content, services, nil
}

type tokenPosition string

func modulePath(methods []Method) (string, error) {
	for _, method := range methods {
		const suffix = "/app/services"
		if strings.HasSuffix(method.PackagePath, suffix) {
			return strings.TrimSuffix(method.PackagePath, suffix), nil
		}
	}
	return "", errors.New("discover module path: no marked method belongs to app/services")
}

func importAliases(paths map[string]struct{}) map[string]string {
	ordered := make([]string, 0, len(paths))
	for path := range paths {
		ordered = append(ordered, path)
	}
	sort.Strings(ordered)
	aliases := make(map[string]string, len(ordered))
	used := map[string]bool{"context": true, "fmt": true, "slog": true, "time": true, "frameworklogging": true, "problem": true, "appRuntime": true}
	for _, importPath := range ordered {
		base := identifier(filepath.Base(importPath))
		alias := base
		for suffix := 2; used[alias]; suffix++ {
			alias = fmt.Sprintf("%s%d", base, suffix)
		}
		used[alias] = true
		aliases[importPath] = alias
	}
	return aliases
}

func identifier(value string) string {
	var builder strings.Builder
	for _, char := range value {
		if unicode.IsLetter(char) || unicode.IsDigit(char) || char == '_' {
			builder.WriteRune(char)
		}
	}
	if builder.Len() == 0 {
		return "generatedpkg"
	}
	return builder.String()
}

func selectedTools(methods []Method) []toolData {
	var tools []toolData
	for _, method := range methods {
		if method.MCP == nil {
			continue
		}
		tools = append(tools, toolData{
			Name:        method.MCP.Name,
			Description: method.Description,
			PackagePath: method.PackagePath,
			Service:     method.Service,
			Method:      method.Name,
			ReadOnly:    method.MCP.ReadOnly,
			Destructive: method.MCP.Destructive,
		})
	}
	return tools
}

func renderGo(source string, data any) ([]byte, error) {
	parsed, err := template.New("generated").Parse(source)
	if err != nil {
		return nil, fmt.Errorf("parse generated Go template: %w", err)
	}
	var output bytes.Buffer
	if err := parsed.Execute(&output, data); err != nil {
		return nil, fmt.Errorf("execute generated Go template: %w", err)
	}
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w\n%s", err, output.String())
	}
	return formatted, nil
}

func goComment(value string) string {
	return strings.ReplaceAll(value, "\n", "\n// ")
}

func slicesContains(values []string, value string) bool {
	for _, candidate := range values {
		if candidate == value {
			return true
		}
	}
	return false
}

const desktopTemplate = `{{.Header}}package desktop

import (
	"context"
	"fmt"
	"log/slog"
	"{{.ProblemPath}}"
	appRuntime "{{.RuntimePath}}"
	"time"
{{- range .Imports }}
	{{.Alias}} "{{.Path}}"
{{- end }}
)
{{range .Services}}
{{$service := .}}
{{range .Methods}}
// {{.Response}} is the concrete desktop response for {{.Name}}.
type {{.Response}} struct {
	Data *{{.Output}} ` + "`json:\"data\"`" + `
	Problem *problem.Problem ` + "`json:\"problem\"`" + `
}
{{end}}
// {{.Name}} exposes only generated feature operations to MyGo.
type {{.Name}} struct {
	readiness *appRuntime.Readiness
	resolve func() (*{{.Type}}, *slog.Logger, error)
}

// New{{.Name}} constructs a desktop adapter without resolving runtime services.
func New{{.Name}}(readiness *appRuntime.Readiness, resolve func() (*{{.Type}}, *slog.Logger, error)) *{{.Name}} {
	return &{{.Name}}{readiness: readiness, resolve: resolve}
}
{{range .Methods}}
// {{.Description}}
func (a *{{$service.Name}}) {{.Name}}(ctx context.Context, input {{.Input}}) {{.Response}} {
	startedAt := time.Now()
	service, logger, err := a.dependencies(ctx)
	if err != nil {
		return {{.Response}}{Problem: desktopProblem(ctx, logger, "{{.Command}}", startedAt, err)}
	}
	output, err := service.{{.Name}}(ctx, input)
	if err != nil {
		return {{.Response}}{Problem: desktopProblem(ctx, logger, "{{.Command}}", startedAt, err)}
	}
	return {{.Response}}{Data: &output}
}
{{end}}
func (a *{{.Name}}) dependencies(ctx context.Context) (*{{.Type}}, *slog.Logger, error) {
	if err := a.readiness.Wait(ctx); err != nil {
		return nil, nil, fmt.Errorf("wait for {{.RuntimeLabel}} runtime: %w", err)
	}
	return a.resolve()
}
{{end}}
`

